def _settings_split_enabled() -> bool:
    """v1.4 — env toggle for 3-way extractor split (default on)."""
    raw = os.getenv("SETTINGS_EXTRACTOR_SPLIT_ENABLED", "1").strip().lower()
    return raw not in ("0", "false", "no", "off", "")


def _strip_fences(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        lines = text.split("\n")
        lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        text = "\n".join(lines).strip()
    return text


class SettingsExtractionError(RuntimeError):
    """A model/format failure is not a successful empty extraction."""


def _validate_fields(data: object, fields: tuple[str, ...]) -> dict:
    if not isinstance(data, dict):
        raise SettingsExtractionError("设定提取格式无效")
    required = {"characters": ("name",), "world_rules": ("category", "rule_text"),
                "relationships": ("source_name", "target_name", "rel_type")}
    result = {}
    for field in fields:
        values = data.get(field)
        if not isinstance(values, list):
            raise SettingsExtractionError("设定提取缺少完整资料列表")
        for value in values:
            if not isinstance(value, dict) or any(not isinstance(value.get(key), str) or not value[key].strip()
                                                  for key in required[field]):
                raise SettingsExtractionError("设定提取包含无效资料条目")
        result[field] = values
    return result


def _validate_relationships(data: dict) -> dict:
    names = [item["name"].strip() for item in data["characters"]]
    if len(names) != len(set(names)):
        raise SettingsExtractionError("设定提取包含重复人物")
    for relationship in data["relationships"]:
        source, target = relationship["source_name"].strip(), relationship["target_name"].strip()
        if source not in names or target not in names or source == target:
            raise SettingsExtractionError("人物关系与角色列表不一致")
    return data


async def _extract_stream(task_type: str, system_prompt: str, outline_text: str,
                          fields: tuple[str, ...], project_id=None) -> dict:
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": f"大纲原文：\n\n{outline_text}"},
    ]
    try:
        router = await get_model_router_async()
        result = await router.generate(task_type=task_type, messages=messages,
            _log_meta={"project_id": str(project_id) if project_id else None, "task_type": task_type})
        data = json.loads(_strip_fences(result.text))
    except Exception as exc:
        raise SettingsExtractionError("设定提取调用失败或返回格式无效") from exc
    return _validate_fields(data, fields)


async def extract_settings_from_outline(outline_text: str, *, project_id=None) -> dict:
    """Return a complete validated extraction, or fail before any persistence.

    An explicit empty list is valid. Missing/failed branches are never silently
    converted to empty lists. The legacy all-branches-failed fallback is bounded
    to one combined call; partial failure asks the caller to retry explicitly.
    """
    fields = ("characters", "world_rules", "relationships")
    if _settings_split_enabled():
        # 2026-11-21 修复:三个 pass 此前是**并行**的,而 relationships pass 看不到
        # characters 名单,却被 _validate_relationships 要求"人名必须字面一致" ——
        # 真实项目上稳定失败(实测 3/3 次 502 "人物关系与角色列表不一致",
        # 连带 world_rules 永远为 0,写作链因此卡在 "世界规则暂时无法读取")。
        # 改为 characters 先出,再把可用名单作为硬约束喂给 relationships pass。
        characters_result = await _extract_stream(
            "characters_extraction", CHARACTERS_EXTRACTOR_SYSTEM, outline_text,
            ("characters",), project_id,
        )
        usable_names = [
            str(item.get("name") or "").strip()
            for item in characters_result["characters"]
            if isinstance(item, dict) and str(item.get("name") or "").strip()
        ]
        relationships_prompt = RELATIONSHIPS_EXTRACTOR_SYSTEM
        if usable_names:
            relationships_prompt += (
                "\n- 本次只能使用下列角色名作为 source_name/target_name,必须逐字一致;"
                "名单之外的人一律不要出现在 relationships 里:"
                + "、".join(usable_names)
            )
        results = await asyncio.gather(*[
            _extract_stream(task, prompt, outline_text, (field,), project_id)
            for task, prompt, field in (
                ("world_rules_extraction", WORLD_RULES_EXTRACTOR_SYSTEM, "world_rules"),
                ("relationships_extraction", relationships_prompt, "relationships"),
            )
        ], return_exceptions=True)
        outcomes = [characters_result, *results]
        failures = [result for result in outcomes if isinstance(result, BaseException)]
        if any(isinstance(result, asyncio.CancelledError) for result in failures):
            raise asyncio.CancelledError
        if not failures:
            return _validate_relationships({field: result[field] for field, result in zip(fields, outcomes)})
        if len(failures) != len(outcomes):
            raise SettingsExtractionError("设定提取尚未完整完成,未写入任何资料,请重试")
        logger.warning("All settings extraction branches failed; trying one combined extraction")
    result = await _extract_stream("extraction", SETTINGS_EXTRACTOR_SYSTEM, outline_text, fields, project_id)
    return _validate_relationships(result)
