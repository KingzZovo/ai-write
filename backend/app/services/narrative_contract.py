WORLD_LOGIC_CONTRACT = """\
【世界逻辑合同：按本书事实与作者要求写作】
作者本轮明确要求决定任务、视角、题材与本章应完成的事件；已提供的正文和有来源的记录说明已经发生的事实，大纲说明待发生的安排。风格参考只能影响表达，不能替换人物关系、数量、时间、规则或剧情结果。
先核对时间、人物位置与状态、物件数量与持有人、信息来源、制度权限以及本章结果。事实冲突要修清楚；不能把规划当成已发生的事实，也不能为消除冲突篡改前文。
路径、时间和资源按具体场景判断。关着的窗不能凭空递物，受限制的角色不能突然获得权限；但日常移动可合理省略，不要求每一步开门、迈脚都写出。善意帮助、顺利交接和无损成功都可以成立，不能一律新增受伤、损失、设饵或阻挠。
人物的判断须符合其已知信息；猜测与确认应区分。已获得充分支持的结论可以确认，不为制造悬念一律保留替代解释。作者安排本章揭晓的内容要揭晓，安排以后兑现的内容不能提前兑现。
能力、工具和制度遵守本书已建立的条件与边界；涉及关键结果时补足读者理解所需的信息。普通钥匙开普通锁无需虚构冷却、反制或失败成本。
补写连接动作、环境与人物反应可以使事件自然成立；不得擅自新增能改变主线的关键资源、人物关系、规则或捷径。确有互相排斥的要求时保留冲突供复核，不能悄悄把必须完成的结果改成未完成。
"""

SCENE_CONTRACT_FIELDS_PROMPT = """\
【场景合同字段】
每个 scene JSON 保留 title/brief/pov/location/time_cue/key_action/target_words/hook，并填写以下字段。字段是写作准备，不是小说正文；可以简洁说明“无变化”或“不涉及”，不要为了填表制造剧情。
title/brief/pov/location/time_cue/key_action/hook 使用文字，brief 不能为空；target_words 使用 JSON 正整数。下列台账可以用文字或有内容的 JSON 对象/数组，保留人物、数量和状态；不要只填 true/false 或空容器。
brief 说明人物此刻所求、在已知处境下为什么采取这个行动、对方如何回应以及本场实际改变什么。把篇幅留给影响选择或结果的关键一刻，说明需要展开的动作连接；普通过渡可简写。动机依据已有经历与关系，不为补解释编造债务、旧怨或新规则。
- start_state：本场承接的实际人物、地点、物件与进展。
- time_delta：相对前场的时间；同一谈话可写连续，无需强加时间跳跃。
- location_path：本场需要交代的移动或递物路径；同地延续如实说明。
- entity_transfers：物件、信息或资源从谁到谁、留在哪里；无交接则写无。
- power_resource_map：人物可用资源、权限和实际限制；普通合作无需虚构双方对抗或代价。
- information_state：关键人物已知、未知或误解的事；区分作者/读者已知与人物已知。
- mechanism_limits：与本场结果相关的已设规则；普通日常行为可写不涉及特殊机制。
- result_strength：作者要求本场达到的具体结果，区分承诺、尝试、完成、确认或仍待后续；不能统一降为疑点。
- transition_bridge：本场结束后留给下一场的实际状态；末场按本章要求收束。
- continuity_ledger:关键人物和物件从场初到场末的变化,明确持有人、位置和知情变化;未变化的事实继续有效。
- cast_sources:本场出现的人和可用资源只能来自作者要求与已写正文。需要有人阻挠或帮忙时,优先让已经出现的人来做;不得为推进剧情补出亲属、帮手、债主、雇主或一笔新的钱。局面一时解决不了,就让它保持未解决。
以下字段仅在相关情形补充:action_budget(紧迫场景可用时间与必要动作是否匹配)、inference_ledger(存在推理时的证据与结论)、evidence_strength(证据实际能支持什么)、npc_disclosure_budget(人物愿意透露什么及原因,不限碎片数)、actor_boundary(立场变化的缘由)、foreshadow_seed(伏笔按本章要求埋设或回收)、register_guard(语言与本书时代和人物身份的关系)、money_totals(本场涉及算钱、结算或收付时,给出总额与口径,写成"名目=数额(依据)";不涉及就不写这个字段,不要凭空编造数目)。
自然事件可放在同一场。既不重复已经完成的交接，也不将多个事件强拆成固定数量的执行单元。合理省略不等于缺少因果，关键阻隔则不能省略。
"""

WRITER_CONTRACT_PROMPT = """\
【正文写作合同】
- 本场按作者要求和场景任务续写,完整正文才是已经发生的事实。场景计划只是安排;前场没有实际完成的事,不能当成已完成。
- 本场承担的到期事件应写到实际结果;未到期事项不提前兑现。结尾可以确认、收束、留下问题或平静交代明日安排,服从本章要求,不强塞悬念。
- 核对同一人物的衣着、伤势、位置与知情范围,同一物件的数量、编号、持有人和存放处;变化要有相应动作或时间,不能无故重置。
- 影响结果的交接、阻隔和权限要写清。正常转场可省略,读者能理解的动作不要逐步解说;人物有能力且愿意配合时可以顺利完成,不必新增损失或误会。
- 人物说话应回应具体处境和对方的话。停顿、心理描写、长对白、直接表达意图、短问短答都可以使用,不设数量或比例配额,不为制造潜台词删掉必要信息。
- 详略围绕人物的选择和事情发生变化的那一刻。影响成败的动作要让读者看得见怎样衔接,态度变化要接得上前面的感受和对方的回应;不能只用“稳稳完成”或笼统的情绪评语替代关键过程。平常步骤可省略,已有铺垫也无需反复解释。
- 准确的动作和物件名称可以重复。判断重复是否有用,要看处境、回应和意义是否变化,不为避重换成失真的近义词。
- 解决问题只用作者已经给出的人和资源。必须出现新的人才能推进时,写成不具名的过路人,并且不改变家庭、经济、身份与关系事实;不要给人物补出作者没写的亲属、合伙人或债主,也不要临时多出一笔钱、一条门路、一项本事或一件可用之物。已有的困难按既有条件推进,实在解决不了就让它保持在未解决状态。
- 设定引用自洽:关键工具和制度按本书事实起作用,补足读者理解动作所需的信息;不为普通器物添加不存在的成本、副作用或失败风险。
- 已设定的条件在人物实际用到时以动作、代价或结果体现;不要替设定再解释一遍原理、次数与上限,也不要反复强调同一件法器、凭证或规矩有多重要。人物自己说出关键条件可以,但不要借旁白替读者复习设定。
- 开场直接进入人物此刻的处境与动作。天气、光线、声响和比喻只在改变人物的感受或选择时写;不要用通用强度意象(如“如墨”“如刀”“如落叶”“如潮水”)起手,也不要在同一段里连用多个比喻来制造气氛。
- 感知锚定:限知视角不直接进入其他人的内心或身体感觉;可观察的外部细节无需每句加感知动词。全知和多视角按作者约定执行。
- 时代语域一致性:服从本书时代、世界设定与人物身份,不能仅凭通用词表否定作品有意安排的穿越、技术或口语。
- 语言准确自然,详略围绕人物处境和情节展开。不得以删短正文、清零词频或达到固定对白比例证明质量提高,也不为凑字数重复感慨和说明。
- 只输出正文,不输出规划、自检、独立章节编号或结束标签;人物正常讨论书籍章节不算结构泄漏。
"""

EVALUATOR_CONTRACT_PROMPT = """\
【事实与完成度评审】
先读完正文，再按作者要求与前文事实核查。按时间顺序追踪同一人物、物件与结果；前后差异须连同中间变化一起判断。
- time_rule_violation：已明确的日期、时刻、先后顺序或时间窗口与行动冲突。
- space_rule_violation：已写明的位置、阻隔或路径使关键动作无法成立；正常上车、出门等合理省略不自动算瞬移。
- power_resource_violation：人物实际缺少完成动作所需的权限或资源，却无来源获得；善意合作、无损成功本身不是违规。
- information_rule_violation：人物没有来源却掌握关键消息，或证据只能支持猜测却被写成确认；已有充分依据的确认不需降级。
- mechanism_rule_violation：关键动作违反本书已建立的机制条件或边界；不能给普通器物强加冷却、代价和反制要求。
- result_strength_violation：正文结果超出作者要求或已有证据，或把作者要求确认的结果擅自降为疑点；以本章具体要求为准。
- chapter_completion_violation：本章到期事件没有实际落实，只有打算、尝试、承诺，或被别的结果替代。未来任务与有意留白不算本章欠缺。
- cognition_violation：违反指定视角、人物知情范围或保留的信息差；可观察的外部细节不必逐句写“看见”，他人的内心和触觉则不能无授权直接进入。
- expression_contract_violation：具体表达妨碍理解、人物声音或情绪可信度；词频、长短句、停顿和对白比例不能单独作证。
- mundane_plausibility_violation：衣着、身体状态、数量、编号、持有人或物件去向与已写事实冲突。未说明的惯例不是本书规则，不凭摊位类型、口袋现金等替作者补前提。
每条问题须提供能逐字定位的 quote，并说明与哪项已写事实或作者要求冲突；不能拼接引文、添加原文没有的动作或替作者修好后再评分。引文存在只说明位置可核对，不说明诊断必然成立。不确定的推测不得当成确定违规。
严重程度按对阅读与剧情的实际影响判断。导致本章核心事件不成立的冲突应体现在对应维度分数，不能因语言流畅而忽略；不按固定关键词封顶。
"""

REVISE_CONTRACT_PROMPT = """\
【通用重写合同】
先将诊断与完整原文、作者要求及前文事实逐一核对；误报不能执行。不把通用修法当作新剧情，也不为让评审满意改变作者要求的结果。
- time_rule_violation / space_rule_violation：修正实际冲突的时间、位置、路径或阻隔；保留正常省略，不逐步补写所有日常动作。
- power_resource_violation / mechanism_rule_violation：以已经建立的资源、权限与机制为准，补必要连接或改正冲突动作；不得统一新增损失、设饵、冷却、伤势或制度。
- information_rule_violation / cognition_violation：纠正无来源知情和指定视角越界；有证据的确认保持确认，弱证据才保留猜测；不靠处处加“看见”掩盖他人内心越界。
- result_strength_violation / chapter_completion_violation：按作者本章要求落实结果，承诺不代替交付。需要修补连接动作时只作最小调整；不能把必须完成的事件降成疑点、拖到下一章或改成失败来避开问题。
- mundane_plausibility_violation：追踪同一人物和物件，修正数量、状态、持有人、位置等具体冲突，保留没有问题的原句。
- expression_contract_violation：只修改有依据且影响阅读的表达；普通停顿、回忆、长对白、直接表达意图和有作用的重复不强制删除。
跨章复发的问题也须重新核对当前原文，不能由历史标签推断本章必有同样错误。修订后复查事件完整性、人物关系、信息范围和物件去向，避免修一处又改坏另一处。
保留全部未涉及的情节、细节和段落。无法在作者要求内解决的冲突应留待复核，不擅自虚构关键事实，也不将未解决说成已解决。
"""

EVALUATOR_CALIBRATION_PROMPT = """\
【评审校准】
先查事实与本章到期事件，再评价人物、语言和节奏；不要先决定高分或返工，再为结论找理由。无问题与有问题都以原文为依据，不预设 accept 应占多数。
审美偏好仅作低严重度建议，不冒充因果错误。平静的交接、自然的沉默、相似的应答可以符合场景；是否平淡或失真须说明具体影响。
大纲允许的自然扩写和合理省略不算偏离；但作者明确要求完成的事件、视角、人物关系、数量和时间不能以“合理取舍”豁免。
每条问题应有逐字 quote 和具体诊断。没有发现问题不等于已经证明完美，不以空洞表扬占用 issues。
"""

REVISE_CALIBRATION_PROMPT = """\
【修订校准】
核实问题后才修改。审美建议不强制动结构；有明确事实矛盾时，即使原评分很高也应纠正。保留原稿可取的表达，不因计数降低或篇幅缩短宣称改善；若候选没有解决具体问题，不把它当成更好的稿件。
"""


def contract_block(*, include_scene_fields: bool = False, include_writer: bool = False) -> str:
    """Compose a compact contract prompt block for generation paths."""
    parts = [WORLD_LOGIC_CONTRACT, contract_hard_gate_prompt()]
    if include_scene_fields:
        parts.append(SCENE_CONTRACT_FIELDS_PROMPT)
    if include_writer:
        parts.append(WRITER_CONTRACT_PROMPT)
    return "\n\n".join(parts)
